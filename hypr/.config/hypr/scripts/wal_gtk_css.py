#!/usr/bin/env python3
"""Write libadwaita named colours from pywal, for adw-gtk3 (GTK3) and GTK4.

Same palette as wal_kde_colors.py, so GTK and Qt apps match.

usage: wal_gtk_css.py COLORS_JSON OUT_CSS [GTK_VERSION]

GTK4 also gets the colours as CSS variables (:root { --accent-bg-color })
which newer libadwaita-style themes use; GTK3 does not understand them.
"""

import json
import os
import sys
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from wal_kde_colors import palette, shade  # noqa: E402


def hexc(rgb):
    return "#" + "".join(f"{round(c * 255):02x}" for c in rgb)


def main(colors_json, out_css, gtk_version="3"):
    p = palette(json.loads(Path(colors_json).read_text()))
    win, view, fg = p["window"], p["view"], p["fg"]
    raised = shade(win, 0.05)

    colors = {
        "accent_color": p["accent"],
        "accent_bg_color": p["accent"],
        "accent_fg_color": win,
        "window_bg_color": win,
        "window_fg_color": fg,
        "view_bg_color": view,
        "view_fg_color": fg,
        "headerbar_bg_color": p["header"],
        "headerbar_fg_color": fg,
        "headerbar_backdrop_color": win,
        "sidebar_bg_color": p["header"],
        "sidebar_fg_color": fg,
        "secondary_sidebar_bg_color": win,
        "secondary_sidebar_fg_color": fg,
        "card_bg_color": raised,
        "card_fg_color": fg,
        "dialog_bg_color": raised,
        "dialog_fg_color": fg,
        "popover_bg_color": raised,
        "popover_fg_color": fg,
        "thumbnail_bg_color": raised,
        "thumbnail_fg_color": fg,
    }
    lines = ["/* generated by wal_gtk_css.py (wal mode); removed by `waybar-wal off` */"]
    lines += [f"@define-color {k} {hexc(v)};" for k, v in colors.items()]
    if gtk_version == "4":
        lines.append(":root {")
        lines += [f"  --{k.replace('_', '-')}: {hexc(v)};" for k, v in colors.items()]
        lines.append("}")
    Path(out_css).write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(*sys.argv[1:4])
