#!/usr/bin/env python3
"""Build a waybar stylesheet whose palette comes from pywal.

Takes the base style.css, drops its @define-color lines and prepends a palette
derived from ~/.cache/wal/colors.json. Wallpaper colours are lightened into
pastels (hue kept) until the dark pill text has a contrast ratio >= 7.

usage: wal_waybar_css.py COLORS_JSON BASE_CSS OUT_CSS  (also used for wlogout)
"""

import colorsys
import json
import re
import sys
from pathlib import Path

MIN_CONTRAST = 7.0

# palette name in style.css -> wal colour it is derived from
MAPPING = {
    "gold": "color3",  # workspaces
    "rose": "color1",  # cpu / temp / ram / gpu
    "iris": "color5",  # window title / spotify
    "pine": "color4",  # disks / battery
    "foam": "color6",  # network / audio / tray
    "leaf": "color2",  # clock
}
LOVE = "#eb6f92"  # critical states stay red regardless of wallpaper


def hex_to_rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i : i + 2], 16) / 255 for i in (0, 2, 4))


def rgb_to_hex(rgb):
    return "#" + "".join(f"{round(c * 255):02x}" for c in rgb)


def luminance(rgb):
    def lin(c):
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4

    r, g, b = (lin(c) for c in rgb)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast(a, b):
    la, lb = sorted((luminance(a), luminance(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def pastel(rgb, text):
    """Lighten (and tame saturation) until text on it is readable."""
    h, l, s = colorsys.rgb_to_hls(*rgb)
    s = min(max(s, 0.35), 0.65)  # keep some colour, avoid neon
    l = max(l, 0.6)
    while l < 0.97:
        out = colorsys.hls_to_rgb(h, l, s)
        if contrast(out, text) >= MIN_CONTRAST:
            return out
        l += 0.01
    return colorsys.hls_to_rgb(h, 0.97, s)


def darken_until(rgb, max_lum=0.02):
    h, l, s = colorsys.rgb_to_hls(*rgb)
    while luminance(colorsys.hls_to_rgb(h, l, s)) > max_lum and l > 0:
        l -= 0.01
    return colorsys.hls_to_rgb(h, max(l, 0), s)


def main(colors_json, base_css, out_css):
    wal = json.loads(Path(colors_json).read_text())
    colors = wal["colors"]

    # Dark text/base taken from the wallpaper, forced dark enough for pills
    base = darken_until(hex_to_rgb(wal["special"]["background"]))

    palette = {"base": rgb_to_hex(base), "text": rgb_to_hex(base), "love": LOVE}
    for name, key in MAPPING.items():
        palette[name] = rgb_to_hex(pastel(hex_to_rgb(colors[key]), base))

    css = Path(base_css).read_text()
    css = re.sub(r"^@define-color .*\n", "", css, flags=re.M)
    # The output lives elsewhere, so pin relative url("./x") to the base CSS dir
    base_dir = Path(base_css).resolve().parent
    css = re.sub(r'url\("\./', f'url("file://{base_dir}/', css)

    header = [f"/* generated by wal_waybar_css.py from {wal.get('wallpaper', '?')} */"]
    header += [f"@define-color {k} {v};" for k, v in palette.items()]

    out = Path(out_css)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(header) + "\n\n" + css)


if __name__ == "__main__":
    main(*sys.argv[1:4])
